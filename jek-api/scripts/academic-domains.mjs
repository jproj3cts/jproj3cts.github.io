// Rebuilds src/academic-domains.js, the universities' email domains the academic price accepts, from a public
// register: Hipo's university-domains-list (MIT licence, about 10,000 universities in 200 countries).
//   node scripts/academic-domains.mjs            (fetches the register)
//   node scripts/academic-domains.mjs world.json (from a copy)
// Domains the .ac/.edu rule in src/academic.js catches already are left out, and so are blog and site hosts,
// where anyone can have an address, and government and military domains. Run it now and then, read the diff, run the tests, deploy.
import { readFileSync, writeFileSync } from 'node:fs';

const REGISTER = 'https://raw.githubusercontent.com/Hipo/university-domains-list/master/world_universities_and_domains.json';
const SUFFIX = /\.(ac|edu)(\.[a-z]{2})?$/;
const HOSTS = /(^|\.)(blogspot|wordpress|wixsite|weebly|github|gitlab|netlify|vercel|herokuapp|googlesites|sites\.google|tumblr|medium)\.[a-z.]+$/;
// public mail and broad second-level domains: never a university's alone
const NEVER = new Set(['gmail.com', 'googlemail.com', 'outlook.com', 'hotmail.com', 'live.com', 'yahoo.com', 'icloud.com', 'aol.com', 'qq.com', '163.com', '126.com',
  'mail.ru', 'yandex.ru', 'proton.me', 'protonmail.com', 'gmx.de', 'gmx.net', 'web.de', 'naver.com', 'rediffmail.com']);
// a government's or an army's domain covers far more people than its college
const GOV = /(^|\.)(gov|mil|army|police)\./;
const broad = d => d.split('.').length < 2 || /^(com|org|net|gov|edu|ac|co|or|go|mil|int|sch|nic)\.[a-z]{2}$/.test(d);

const src = process.argv[2] ? readFileSync(process.argv[2], 'utf8') : await (await fetch(REGISTER)).text();
const list = JSON.parse(src);
const out = new Set();
for (const u of list) for (const raw of u.domains || []) {
  const d = String(raw).trim().toLowerCase().replace(/^www\./, '').replace(/\.$/, '');
  if (!/^[a-z0-9-]+(\.[a-z0-9-]+)+$/.test(d) || SUFFIX.test(d) || HOSTS.test(d) || NEVER.has(d) || GOV.test(d) || broad(d)) continue;
  out.add(d);
}
const sorted = [...out].sort();
const lines = [];
for (let i = 0; i < sorted.length; i += 8) lines.push('  ' + sorted.slice(i, i + 8).map(d => `'${d}'`).join(', ') + ',');
writeFileSync(new URL('../src/academic-domains.js', import.meta.url), `// Generated by scripts/academic-domains.mjs: do not edit by hand.
// Universities' email domains from Hipo's university-domains-list (https://github.com/Hipo/university-domains-list,
// MIT licence), ${list.length} universities; those the .ac/.edu rule catches already left out.
// Built ${new Date().toISOString().slice(0, 10)}.
export const REGISTER_DOMAINS = new Set([
${lines.join('\n')}
]);
`);
console.log(`${list.length} universities, ${sorted.length} domains written`);

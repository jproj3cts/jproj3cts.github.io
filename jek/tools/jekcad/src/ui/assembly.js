/* ==========================================================================
   Tabs and assemblies. The document's tabs run along the bottom: Part Studios and Assemblies, one open at a time.
   An Assembly shows parts of the Part Studios where its instances put them. Insert adds an instance; a part is
   dragged about (Ctrl: turned about the line of sight), or placed by the numbers in its panel, or fixed; a mate
   joins a face of one to a face of another (the mate's kind is what it leaves free), and the mates are solved again
   whenever anything moves. Each Part Studio is regenerated by the kernel when it has changed, and its parts' meshes
   are kept here; an instance is drawn as its part's mesh, moved.
   ========================================================================== */
const STUDIO = new Map();       // a studio's tab id → { key, parts } (its parts' meshes, as the kernel sent them)
const BAKED = new Map();        // an instance's id → { key, part } (its mesh where the instance puts it)
export const AS = { mate: null, drag: null, insertBusy: false };
const tabOf = id => app.file.tabs.find(t => t.id === id);
const studios = () => app.file.tabs.filter(t => t.kind === 'studio');
/* a studio's parts, regenerated if it has changed since they were last made */
async function studioParts(t) {
  const key = JSON.stringify(t), had = STUDIO.get(t.id);
  if (had && had.key === key) return had.parts;
  const out = await kernelAsk('regen', { doc: t, opts: {} }, 'regen');
  if (!out) return null;                       // replaced by a newer request
  STUDIO.set(t.id, { key, parts: out.parts });
  return out.parts;
}
/* the mesh of a studio's part as last made (for a connector, which is in the part's own coordinates) */
function localMesh(I) { const s = STUDIO.get(I.studio); return s ? s.parts.find(p => p.id === I.part) : null; }
/* a part's mesh moved to where an instance puts it */
function bake(M, I, look) {
  const mv = (src, turnOnly) => { const out = new Float32Array(src.length); for (let k = 0; k < src.length; k += 3) { const v = turnOnly ? turned3(I, [src[k], src[k + 1], src[k + 2]]) : placed(I, [src[k], src[k + 1], src[k + 2]]); out[k] = v[0]; out[k + 1] = v[1]; out[k + 2] = v[2]; } return out; };
  const pos = mv(M.pos), lo = [Infinity, Infinity, Infinity], hi = [-Infinity, -Infinity, -Infinity];
  for (let k = 0; k < pos.length; k += 3) for (let i = 0; i < 3; i++) { lo[i] = Math.min(lo[i], pos[k + i]); hi[i] = Math.max(hi[i], pos[k + i]); }
  return Object.assign({}, M, { id: I.id, pos, nrm: mv(M.nrm, true), seg: mv(M.seg), verts: mv(M.verts), bbox: pos.length ? [lo, hi] : M.bbox, centroid: M.centroid ? placed(I, M.centroid) : M.centroid, look: Object.assign({}, look, { name: I.name || look.name, hidden: !!I.hidden }), inst: I.id });
}
/* the assembly shown: every studio it uses made, every instance's mesh put in its place */
export async function asmRegen() {
  const A = app.asm;
  if (!A) return null;
  app.busy = true; emit('busy');
  try {
    for (const sid of new Set(A.instances.map(I => I.studio))) { const t = tabOf(sid); if (t && !(await studioParts(t))) return null; }
  } catch (err) { app.busy = false; emit('busy'); app.error = err.message; toast('A Part Studio of this assembly could not be made: ' + err.message, true); return null; }
  if (app.asm !== A) return null;
  // a mate's connectors found again on their faces (a part changed in its studio keeps its mates where the faces went)
  let moved = false;
  for (const m of A.mates) for (const c of [m.a, m.b]) {
    const I = A.instances.find(x => x.id === c.inst), M = I && localMesh(I);
    if (!M || !c.face || !M.faceNames) continue;
    let best = -1, bd = Infinity;
    M.faceNames.forEach((nm, i) => { if (nm !== c.face) return; const k = faceConnector(M, i); if (!k) return; const d = Math.hypot(k.o[0] - c.o[0], k.o[1] - c.o[1], k.o[2] - c.o[2]); if (d < bd) { bd = d; best = i; } });
    if (best < 0) continue;
    const k = faceConnector(M, best);
    if (bd > 1e-9 || Math.hypot(k.z[0] - c.z[0], k.z[1] - c.z[1], k.z[2] - c.z[2]) > 1e-9) { Object.assign(c, { o: k.o, z: k.z, x: k.x }); moved = true; }
  }
  if (moved) solveMates(A);
  showAsm();
  app.busy = false; app.error = null; app.regenCount++;
  emit('busy');
  return app.result;
}
/* the instances as the view's parts (only the ones that moved are made again) */
function showAsm() {
  const A = app.asm, parts = [], live = new Set();
  for (const I of A.instances) {
    const t = tabOf(I.studio), s = STUDIO.get(I.studio), i = s ? s.parts.findIndex(p => p.id === I.part) : -1;
    if (i < 0) continue;
    const key = s.key.length + '|' + I.p.join() + '|' + I.q.join() + '|' + (I.hidden ? 1 : 0) + '|' + (I.name || '') + '|' + JSON.stringify(t.parts[I.part] || {});
    let b = BAKED.get(I.id);
    if (!b || b.key !== key || b.src !== s.parts[i]) { b = { key, src: s.parts[i], part: bake(s.parts[i], I, partLook(t, I.part, i)) }; BAKED.set(I.id, b); }
    parts.push(b.part); live.add(I.id);
  }
  for (const id of [...BAKED.keys()]) if (!live.has(id)) BAKED.delete(id);
  app.result = { features: [], parts, frames: {}, vars: {}, errors: [], asm: true };
  app.sel = app.sel.filter(x => !x.part || parts.some(p => p.id === x.part));
  emit('model', app.result);
  renderAsm();
}
/* ---------- tabs ---------- */
export function switchTab(id) {
  if (id === app.file.active) return true;
  if (app.sketch) { toast('Finish the sketch first'); return false; }
  if (app.editing && hooks.cadCloseDialog) hooks.cadCloseDialog();
  mateClose();
  app.file.active = id; app.sel = []; app.picked = null; app.hover = null;
  bindTab();
  emit('tab'); emit('sel');
  if (hooks.cadSaveLater) hooks.cadSaveLater();
  const r = regenNow(); if (r && r.then) r.then(() => fit());
  return true;
}
export function addTab(kind) {
  if (!editGate()) return null;
  if (app.sketch) { toast('Finish the sketch first'); return null; }
  checkpoint();
  const n = app.file.tabs.filter(t => t.kind === kind).length + 1;
  const t = kind === 'assembly' ? normAsm({ name: 'Assembly ' + n }, n) : Object.assign(normDoc({}), { id: sketchId('t'), kind: 'studio', name: 'Part Studio ' + n });
  app.file.tabs.push(t);
  changed();
  switchTab(t.id);
  return t.id;
}
export function renameTab(id, name) {
  const t = tabOf(id); name = String(name || '').trim().slice(0, 120);
  if (!t || !name || name === t.name || !editGate()) return false;
  checkpoint(); t.name = name; changed(); renderTabs(); return true;
}
export function deleteTab(id) {
  const t = tabOf(id);
  if (!t || !editGate()) return false;
  if (t.kind === 'studio' && studios().length === 1) { toast('A document keeps at least one Part Studio'); return false; }
  const used = t.kind === 'studio' ? app.file.tabs.filter(a => a.kind === 'assembly' && a.instances.some(I => I.studio === id)).map(a => a.name) : [];
  if (!confirm('Delete “' + t.name + '”?' + (used.length ? ' Its parts go from ' + used.join(', ') + ' too.' : '') + ' Undo brings it back.')) return false;
  if (app.sketch) { toast('Finish the sketch first'); return false; }
  checkpoint();
  const i = app.file.tabs.indexOf(t);
  app.file.tabs.splice(i, 1);
  for (const a of app.file.tabs) if (a.kind === 'assembly') { a.instances = a.instances.filter(I => I.studio !== id); const live = new Set(a.instances.map(I => I.id)); a.mates = a.mates.filter(m => live.has(m.a.inst) && live.has(m.b.inst)); }
  STUDIO.delete(id);
  if (app.file.active === id) { app.file.active = (app.file.tabs[Math.max(0, i - 1)] || app.file.tabs[0]).id; app.sel = []; app.picked = null; if (app.editing && hooks.cadCloseDialog) hooks.cadCloseDialog(); bindTab(); emit('tab'); }
  changed();
  return true;
}
export function duplicateTab(id) {
  const t = tabOf(id);
  if (!t || !editGate()) return null;
  checkpoint();
  const c = JSON.parse(JSON.stringify(t)); c.id = sketchId('t'); c.name = t.name + ' copy';
  app.file.tabs.splice(app.file.tabs.indexOf(t) + 1, 0, c);
  changed(); renderTabs();
  return c.id;
}
let tabMenu = null;
function closeTabMenu() { if (tabMenu) { tabMenu.remove(); tabMenu = null; } }

// The JEK site navigation and the jek.css stamp have one source each: _includes/site-nav.html and css_v in
// _config.yml. Pages Jekyll builds (front matter, or _layouts/) use {% include site-nav.html %} and
// jek.css?v={{ site.css_v }}. A few files are served unbuilt and keep literal copies (COPIES below); this checks
// those copies still match, and that no page has slipped back to a hand-copied nav or a stale stamp.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const ROOT = path.resolve(import.meta.dirname, '../../../../..');
const read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');
const files = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '*.html'], { cwd: ROOT, encoding: 'utf8' })
  .split('\n').filter((f) => f && fs.existsSync(path.join(ROOT, f)));

// served as they are, so they cannot use Liquid: the browser suite is loaded unbuilt by test/run.mjs, and the
// tool page is generated by build.mjs from jekray/page.html
const COPIES = ['jek/tools/jekray-tests.html'];
const STAMP_ONLY = ['jek/tools/jekray/page.html', 'jek/tools/jekray.html', 'jek/tools/jekray-dev.html'];

const INCLUDE = '{% include site-nav.html %}';
const cssV = read('_config.yml').match(/^css_v:\s*"([^"]+)"/m)?.[1];
const nav = read('_includes/site-nav.html').replace(/^\{% comment %\}[\s\S]*?\{% endcomment -%\}\n/, '');
const squash = (s) => s.replace(/\s+/g, ' ').replace(/> </g, '><').trim();
const built = (f, text) => f.startsWith('_layouts/') || text.startsWith('---\n');
const navBlock = (text) => {
  const i = text.indexOf('<div class="top-container">');
  if (i < 0) return null;
  const j = text.indexOf('<a class="text-overlay"', i);
  return j < 0 ? null : text.slice(i, text.indexOf('</div>', j) + 6);
};

test('css_v is set in _config.yml and the include holds the nav', () => {
  assert.match(cssV ?? '', /^\w+$/);
  assert.ok(nav.startsWith('<div class="top-container">') && nav.includes('data-nav-drop'));
});

test('every JEK page takes the nav from _includes/site-nav.html', () => {
  const bad = [];
  for (const f of files) {
    if (f.startsWith('jek/tools/jekray/') || f === 'jek/tools/jekray-dev.html' || f === '_includes/site-nav.html') continue;
    const text = read(f);
    const hasInclude = text.includes(INCLUDE);
    if (hasInclude && !built(f, text)) bad.push(`${f}: uses the include but has no front matter, so Jekyll copies it verbatim`);
    if (!text.includes('data-nav-drop')) continue;
    if (COPIES.includes(f)) {
      if (squash(navBlock(text) ?? '') !== squash(nav)) bad.push(`${f}: its copy of the nav differs from _includes/site-nav.html`);
    } else bad.push(`${f}: has its own copy of the nav; use ${INCLUDE} (and front matter)`);
  }
  assert.deepEqual(bad, []);
});

test('every jek.css link carries the css_v stamp', () => {
  const bad = [];
  for (const f of files) {
    const text = read(f);
    for (const m of text.matchAll(/jek\.css\?v=(\{\{ site\.css_v \}\}|[^"'\s>]+)/g)) {
      const v = m[1];
      if (v.startsWith('{{')) {
        if (!built(f, text)) bad.push(`${f}: {{ site.css_v }} in a page Jekyll does not build`);
      } else if (v !== cssV) bad.push(`${f}: jek.css?v=${v}, css_v is ${cssV}`);
      else if (built(f, text) && !STAMP_ONLY.includes(f) && !COPIES.includes(f)) bad.push(`${f}: literal stamp; use {{ site.css_v }}`);
    }
  }
  assert.deepEqual(bad, []);
});

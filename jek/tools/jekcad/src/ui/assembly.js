  closeTabMenu();
  tabMenu = h('div', { class: 'rt-menu cad-tabmenu', role: 'menu' }, ...items.map(([label, fn]) => h('button', { type: 'button', role: 'menuitem', onclick: () => { closeTabMenu(); fn(); } }, label)));

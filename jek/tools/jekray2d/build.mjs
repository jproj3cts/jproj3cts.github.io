#!/usr/bin/env node
/* Builds jek/tools/jekray2d.html, the page JEKray2D is served as, from the sources here:
   page.html (the markup, with {{STYLE}} and {{SCRIPT}} where they go), style.css, and the
   modules under src/ in the order of order.json. The modules are ES modules; the page joins
   them into one script in one scope, as the tool has always run, so the build drops each
   module's import lines and export keywords and nothing else. The page is committed: run
   `node build.mjs` after editing a module, or `node build.mjs --check` to see it is current.
   The lint checks that every name a module takes from another is imported from where it
   is declared (or listed in src/state/shared.md), so the modules stay honest about what
   they depend on. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as acorn from './vendor/acorn.mjs';
import * as walk from './vendor/acorn-walk.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const PAGE = path.resolve(HERE, '../jekray2d.html');
const WORKER_LINE = 'if (IN_WORKER) { workerMain(); return; }';     // the worker branch, between the worker's and the page's modules
const read = f => fs.readFileSync(path.join(HERE, f), 'utf8');
export const order = () => JSON.parse(read('order.json'));

/* a module's header (its imports and the shared-state note) and its body: the header is
   everything before the first blank line, when the file opens with an import or the note */
function split(text) {
  const lines = text.split('\n');
  if (!/^(import |\/\/ Shared mutable state)/.test(lines[0])) return { header: '', body: lines };
  const k = lines.indexOf('');
  return { header: lines.slice(0, k).join('\n'), body: lines.slice(k + 1) };
}
/* a module's code as the page carries it */
export function stripModule(text) {
  return split(text).body.map(l => l.startsWith('export ') ? l.slice(7) : l).join('\n');
}
/* the modules loaded directly, for development: an entry that imports them all in order, and
   a page that uses it in place of the built script (workers need the built page: its script
   is what they are started from, so the development page works everything out on the page) */
export function mainModule() {
  return '// Generated by build.mjs from order.json: every module, in the page\'s order. Do not edit.\n' + order().map(f => "import './" + f + "';").join('\n') + '\n';
}
/* the dev page's worker: the modules up to the worker's own, as the built page runs them (WORKER_LINE) */
export function workerModule() {
  const fs = order(); fs.length = fs.indexOf('worker/main.js') + 1;
  return '// Generated by build.mjs from order.json: the modules the worker runs. Do not edit.\n' + fs.map(f => "import './" + f + "';").join('\n') + "\nexport { workerMain } from './worker/main.js';\n";
}
export function devPage() {
  return read('page.html')
    .replace('<style>\n{{STYLE}}\n</style>', () => '<link rel="stylesheet" href="jekray2d/style.css">')
    .replace('<script>\n{{SCRIPT}}\n</script>', () => '<script>self.JEKRAY_DEV_WORKER = new URL("jekray2d/src/worker/entry.js", location.href).href;</script>\n<script type="module" src="jekray2d/src/main.js"></script>')
    .replace('<title>', '<title>Dev: ');
}
export const DEV_PAGE = path.resolve(HERE, '../jekray2d-dev.html'), MAIN = path.join(HERE, 'src/main.js'), WORKER_MAIN = path.join(HERE, 'src/worker-main.js');
export function build() {
  let script = "(() => {\n'use strict';\n\n";
  for (const f of order()) { script += stripModule(read('src/' + f)); if (f === 'worker/main.js') script += WORKER_LINE + '\n'; }
  script += '})();';
  return read('page.html').replace('{{STYLE}}', () => read('style.css').replace(/\n$/, '')).replace('{{SCRIPT}}', () => script);
}

const DECL = /^(?:async\s+)?(function\*?|const|let|var|class)\s+([A-Za-z_$][\w$]*)/;
/* the names a column-0 declaration line declares (a `const a = 1, b = 2` declares two) */
export function declared(line) {
  const m = line.match(DECL);
  if (!m) return null;
  const names = [m[2]];
  if (m[1] === 'const' || m[1] === 'let' || m[1] === 'var') {
    let d = 0, buf = '';
    for (const ch of line.slice(m[0].length)) {
      if ('([{'.includes(ch)) d++; else if (')]}'.includes(ch)) d--;
      if (ch === ',' && d === 0) { const n = buf.match(/^\s*([A-Za-z_$][\w$]*)\s*=/); if (n) names.push(n[1]); buf = ''; } else buf += ch;
    }
    const n = buf.match(/^\s*([A-Za-z_$][\w$]*)\s*=/); if (n && !names.includes(n[1])) names.push(n[1]);
  }
  return { kind: m[1], names };
}
export const parse = text => acorn.parse(text, { ecmaVersion: 2024, sourceType: 'module' });
export const isScope = n => /Function|Program|BlockStatement|For(In|Of)?Statement|SwitchStatement|CatchClause|ClassExpression/.test(n.type);
/* the names each scope declares, so a reference can be told from a local of the same name */
export function scopesOf(ast) {
  const S = new Map(), add = (node, n) => { if (!S.has(node)) S.set(node, new Set()); S.get(node).add(n); };
  const names = (p, out) => { if (!p) return out; switch (p.type) { case 'Identifier': out.push(p.name); break; case 'ObjectPattern': for (const q of p.properties) names(q.type === 'RestElement' ? q.argument : q.value, out); break; case 'ArrayPattern': for (const q of p.elements) names(q, out); break; case 'RestElement': names(p.argument, out); break; case 'AssignmentPattern': names(p.left, out); break; } return out; };
  walk.fullAncestor(ast, (node, st, anc) => {
    const up = re => { for (let i = anc.length - 1; i >= 0; i--) if (re.test(anc[i].type)) return anc[i]; };
    if (node.type === 'VariableDeclaration') { const sc = node.kind === 'var' ? up(/Function|Program/) : up(/BlockStatement|Program|For(In|Of)?Statement|SwitchStatement|CatchClause|Function/); for (const d of node.declarations) for (const n of names(d.id, [])) add(sc, n); }
    else if (/Function/.test(node.type)) { for (const p of node.params) for (const n of names(p, [])) add(node, n); if (node.type === 'FunctionDeclaration' && node.id) add(up(/BlockStatement|Program|For(In|Of)?Statement|SwitchStatement|CatchClause|Function/), node.id.name); if (node.type === 'FunctionExpression' && node.id) add(node, node.id.name); }
    else if (node.type === 'ClassDeclaration' && node.id) add(up(/BlockStatement|Program|Function/), node.id.name);
    else if (node.type === 'ClassExpression' && node.id) add(node, node.id.name);
    else if (node.type === 'CatchClause' && node.param) for (const n of names(node.param, [])) add(node, n);
  });
  return S;
}
/* identifiers that refer to a module-scope binding (not a property, key, label or local) */
export function moduleRefs(ast) {
  const S = scopesOf(ast), out = [];
  walk.fullAncestor(ast, (node, st, anc) => {
    if (node.type !== 'Identifier') return;
    const p = anc[anc.length - 2];
    if (p.type === 'MemberExpression' && p.property === node && !p.computed) return;
    if ((p.type === 'Property' || p.type === 'PropertyDefinition' || p.type === 'MethodDefinition') && p.key === node && !p.computed && !p.shorthand) return;
    if (p.type === 'VariableDeclarator' && p.id === node) return;
    if (/Function|Class/.test(p.type) && (p.id === node || (p.params || []).includes(node))) return;
    if (/^(ImportSpecifier|ImportDefaultSpecifier|ExportSpecifier|LabeledStatement|BreakStatement|ContinueStatement)$/.test(p.type)) return;
    if ((p.type === 'AssignmentPattern' && p.left === node) || p.type === 'RestElement' || p.type === 'ArrayPattern') return;
    for (let i = anc.length - 2; i >= 1; i--) { const a = anc[i]; if (isScope(a) && S.get(a) && S.get(a).has(node.name)) return; }
    out.push(node);
  });
  return out;
}
/* what each module declares, exports, imports and refers to at module scope */
export function scan() {
  const mods = new Map();
  for (const f of order()) {
    const text = read('src/' + f), ast = parse(text);
    const decls = new Map(), exported = new Set(), imports = new Map(), uses = new Set();
    for (const st of ast.body) {
      if (st.type === 'ImportDeclaration') { const to = path.posix.normalize(path.posix.join(path.posix.dirname(f), st.source.value)); for (const s of st.specifiers) imports.set(s.local.name, to); continue; }
      const d = st.type === 'ExportNamedDeclaration' ? st.declaration : st, ex = st.type === 'ExportNamedDeclaration';
      if (!d) continue;
      const names = d.type === 'VariableDeclaration' ? d.declarations.filter(v => v.id.type === 'Identifier').map(v => v.id.name) : d.id ? [d.id.name] : [];
      const kind = d.type === 'VariableDeclaration' ? d.kind : d.type === 'ClassDeclaration' ? 'class' : d.type === 'FunctionDeclaration' ? 'function' : null;
      if (kind) for (const n of names) { decls.set(n, kind); if (ex) exported.add(n); }
    }
    for (const id of moduleRefs(ast)) uses.add(id.name);
    mods.set(f, { decls, exported, imports, uses, ast, text });
  }
  return mods;
}
/* statements a module runs as it loads, other than declarations: allowed only where the data
   the worker needs is set up, and in boot.js, where the page is put together */
const LOAD_OK = { 'core/traps.js': /FACT\.push/, 'engines/fibre.js': /FC\[k\]\.portList/, 'ui/boot.js': /./ };
export function loadTimeStatements(f, text) {
  const ast = parse(text), out = [];
  for (const st of ast.body) {
    if (/Declaration$/.test(st.type)) continue;
    const raw = text.slice(st.start, st.end).split('\n')[0];
    if (LOAD_OK[f] && LOAD_OK[f].test(text.slice(st.start, st.end))) continue;
    out.push({ line: text.slice(0, st.start).split('\n').length, text: raw.slice(0, 80) });
  }
  return out;
}
const ENGINE_SIDE = /^(core|state|parts|engines|worker)\//, LAYER_EXCEPTIONS = new Set();
/* the names a module's top-level initialisers read as the module loads: outside any function, or
   inside one called there and then (an IIFE) */
export function loadTimeReads(ast, text) {
  const out = [], FN = /^(FunctionExpression|ArrowFunctionExpression)$/;
  const refs = moduleRefs(ast), inInit = [];
  for (const st of ast.body) {
    const d = st.type === 'ExportNamedDeclaration' ? st.declaration : st;
    if (!d || d.type !== 'VariableDeclaration') continue;
    for (const v of d.declarations) if (v.init) {
      // the stretches of the initialiser that run now: everything but function bodies not called at once
      const lazy = [];
      walk.recursive(v.init, null, {
        FunctionExpression(n) { lazy.push([n.start, n.end]); }, ArrowFunctionExpression(n) { lazy.push([n.start, n.end]); }, FunctionDeclaration(n) { lazy.push([n.start, n.end]); },
        CallExpression(n, st, c) { if (FN.test(n.callee.type)) { c(n.callee.body, st); for (const a of n.arguments) c(a, st); } else { c(n.callee, st); for (const a of n.arguments) c(a, st); } },
        Property(n, st, c) { if (n.kind === 'get' || n.kind === 'set') lazy.push([n.value.start, n.value.end]); else c(n.value, st); },
      });
      inInit.push([v.init.start, v.init.end, lazy]);
    }
  }
  for (const id of refs) for (const [s, e, lazy] of inInit) if (id.start >= s && id.end <= e && !lazy.some(([a, b]) => id.start >= a && id.end <= b)) out.push([id.name, text.slice(0, id.start).split('\n').length]);
  return out;
}
export function lint() {
  const errors = [], warnings = [], mods = scan();
  for (const f of order()) for (const s of loadTimeStatements(f, read('src/' + f))) errors.push(f + ':' + s.line + ' runs code as it loads (' + s.text.trim() + '): a module only declares; put it in its wire function, called from boot.js');
  // the layers: core, state, engines and the worker know nothing of the page (ui, io, page); the
  // engines reach it through core/hooks.js (LAYER_EXCEPTIONS: modules let through for a while).
  for (const [f, m] of mods) {
    if (!ENGINE_SIDE.test(f) || LAYER_EXCEPTIONS.has(f)) continue;
    const bad = [...new Set([...m.imports.values()].filter(from => !ENGINE_SIDE.test(from)))];
    if (bad.length) errors.push(f + ' imports from the page side (' + bad.join(', ') + '): core, state, engines and the worker reach the page through core/hooks.js');
  }
  for (const f of LAYER_EXCEPTIONS) { const m = mods.get(f); if (m && ![...m.imports.values()].some(from => !ENGINE_SIDE.test(from))) warnings.push(f + ' no longer imports from the page side: take it off LAYER_EXCEPTIONS in build.mjs'); }
  // the page runs the modules in order.json's order, in one scope: a value a module works out as it
  // loads (an object, a table, an IIFE) must not read a const, let or class a later module declares
  { const at = new Map(); [...mods.keys()].forEach((f, i) => at.set(f, i));
    const homeOf = new Map(); for (const [f, m] of mods) for (const [n, kind] of m.decls) if (kind !== 'function') homeOf.set(n, f);
    for (const [f, m] of mods) for (const [n, line] of loadTimeReads(m.ast, m.text)) { const h = homeOf.get(n); if (h && h !== f && at.get(h) > at.get(f)) errors.push(f + ':' + line + ' reads ' + n + ' as it loads, but ' + h + ' comes later in order.json'); } }
  // a module cannot assign another's binding: a shared let is set through its setter (setX)
  for (const [f, m] of mods) walk.simple(m.ast, {
    AssignmentExpression(n) { if (n.left.type === 'Identifier' && m.imports.has(n.left.name)) errors.push(f + ':' + m.text.slice(0, n.start).split('\n').length + ' assigns ' + n.left.name + ', which ' + m.imports.get(n.left.name) + ' declares: use its setter'); },
    UpdateExpression(n) { if (n.argument.type === 'Identifier' && m.imports.has(n.argument.name)) errors.push(f + ':' + m.text.slice(0, n.start).split('\n').length + ' changes ' + n.argument.name + ', which ' + m.imports.get(n.argument.name) + ' declares: use its setter'); },
  });
  const shared = new Set([...read('src/state/shared.md').matchAll(/^- `([\w$]+)`/gm)].map(m => m[1]));
  const home = new Map();
  for (const [f, m] of mods) for (const [n, kind] of m.decls) { if (home.has(n)) errors.push(n + ' is declared in both ' + home.get(n).f + ' and ' + f); home.set(n, { f, kind }); }
  for (const n of shared) { const h = home.get(n); if (!h) errors.push('shared.md lists ' + n + ', which no module declares'); else if (h.kind !== 'let' && h.kind !== 'var') errors.push('shared.md lists ' + n + ', a ' + h.kind + ', which should be imported instead'); }
  for (const [f, m] of mods) {
    for (const [n, from] of m.imports) {
      const h = home.get(n);
      if (!h) errors.push(f + ' imports ' + n + ', which no module declares');
      else if (h.f !== from) errors.push(f + ' imports ' + n + ' from ' + from + ', but it is declared in ' + h.f);
      else if (!mods.get(h.f).exported.has(n)) errors.push(f + ' imports ' + n + ', which ' + h.f + ' does not export');
      if (!m.uses.has(n)) warnings.push(f + ' imports ' + n + ' and does not use it');
    }
    for (const n of m.uses) {
      if (m.decls.has(n) || m.imports.has(n) || shared.has(n)) continue;
      const h = home.get(n);
      if (h) errors.push(f + ' uses ' + n + ' from ' + h.f + ' without importing it');
    }
  }
  return { errors, warnings };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { errors, warnings } = lint();
  for (const w of warnings) console.warn('warning: ' + w);
  if (errors.length) { for (const e of errors) console.error('error: ' + e); process.exit(1); }
  const html = build();
  if (process.argv.includes('--check')) {
    const same = fs.existsSync(PAGE) && fs.readFileSync(PAGE, 'utf8') === html && fs.readFileSync(MAIN, 'utf8') === mainModule() && fs.readFileSync(WORKER_MAIN, 'utf8') === workerModule() && fs.readFileSync(DEV_PAGE, 'utf8') === devPage();
    console.log(same ? 'jekray2d.html is current' : 'jekray2d.html is out of date: run node build.mjs');
    process.exit(same ? 0 : 1);
  }
  fs.writeFileSync(PAGE, html);
  fs.writeFileSync(MAIN, mainModule());
  fs.writeFileSync(WORKER_MAIN, workerModule());
  fs.writeFileSync(DEV_PAGE, devPage());
  console.log('wrote ' + path.relative(process.cwd(), PAGE) + ', ' + html.length + ' bytes from ' + order().length + ' modules, and the dev page');
}
